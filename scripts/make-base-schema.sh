#!/usr/bin/env bash
# Maintainers only: regenerate crates/exact-db/bootstrap/exact_base_schema.sql, the tables EXACT (Django) creates in an empty
# database, which `exact-cli migrate` applies to a new, empty database (so a new installation needs no Django at all).
# Builds EXACT's own image at a fixed commit, runs `manage.py migrate` against a throwaway PostgreSQL 16 and dumps the result
# (schema plus the rows the migrations write: django_migrations, content types, permissions). Needs Docker only.
# Usage: scripts/make-base-schema.sh [EXACT commit]   (default: the commit in the current file's header)
#   EXACT_IMAGE=<image>  reuse the Python environment of an existing EXACT image (e.g. exact-dev-web from EXACT's docker-compose)
#                        instead of building EXACT's Dockerfile (slow); the code of the given commit is copied over it either way.
# Run it after a change to EXACT's models, then check: a database from the new file must still match baseline/ (schema-check)
# and exact-rust's own migrations must still apply on top of it.
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
OUT="$ROOT/crates/exact-db/bootstrap/exact_base_schema.sql"
REPO="${EXACT_REPO:-https://github.com/DeepMicroscopy/Exact.git}"
REF="${1:-$(sed -n 's/^-- EXACT commit: //p' "$OUT" 2>/dev/null | head -1)}"
[ -n "$REF" ] || { echo "usage: $0 <EXACT commit>" >&2; exit 1; }
NAME="exact-base-schema-$$"
SRC="$(mktemp -d)"
cleanup() { docker rm -f "$NAME-db" >/dev/null 2>&1 || true; docker network rm "$NAME" >/dev/null 2>&1 || true; rm -rf "$SRC"; }
trap cleanup EXIT

echo "fetching EXACT $REF"
git clone -q --filter=blob:none "$REPO" "$SRC" && git -C "$SRC" -c advice.detachedHead=false checkout -q "$REF"
REF="$(git -C "$SRC" rev-parse HEAD)"
if [ -n "${EXACT_IMAGE:-}" ]; then
  echo "using the Python environment of $EXACT_IMAGE"
  printf 'FROM %s\nCOPY . /usr/src/exact/\nWORKDIR /usr/src/exact\n' "$EXACT_IMAGE" | docker build -q -t exact-django:"$REF" -f - "$SRC/exact" >/dev/null
else
  echo "building EXACT's image (its Dockerfile)"
  docker build -q -t exact-django:"$REF" "$SRC/exact" >/dev/null
fi
docker network create "$NAME" >/dev/null
docker run -d --name "$NAME-db" --network "$NAME" -e POSTGRES_USER=exact -e POSTGRES_PASSWORD=exact -e POSTGRES_DB=exact postgres:16-alpine >/dev/null
until docker exec "$NAME-db" pg_isready -q -U exact -d exact 2>/dev/null; do sleep 1; done
sleep 2   # the image's entrypoint restarts the server once after initdb
until docker exec "$NAME-db" pg_isready -q -U exact -d exact 2>/dev/null; do sleep 1; done

echo "running Django's migrations"
docker run --rm --network "$NAME" --entrypoint sh \
  -e SQL_ENGINE=django.db.backends.postgresql -e SQL_HOST="$NAME-db" -e SQL_PORT=5432 \
  -e SQL_DATABASE=exact -e SQL_USER=exact -e SQL_PASSWORD=exact \
  exact-django:"$REF" -c 'cp exact/settings.py.example exact/settings.py && python3 manage.py migrate --no-input' | grep -c "Applying" | sed 's/^/migrations applied: /'

echo "dumping"
{
  echo "-- EXACT's base schema: what Django's migrations of EXACT create in an empty database (tables, constraints, indexes, and"
  echo "-- the rows they write: django_migrations, django_content_type, auth_permission). Applied by \`exact-cli migrate\` to an empty"
  echo "-- database only. Generated by scripts/make-base-schema.sh; do not edit by hand."
  echo "-- EXACT commit: $REF"
  echo
  # INSERTs instead of COPY (one SQL text the server can execute); psql meta-commands (\restrict) dropped; the search_path
  # and SET settings kept local to the transaction exact-cli applies this in; the applied-at times of django_migrations made constant.
  docker exec "$NAME-db" pg_dump -U exact -d exact --no-owner --no-privileges --inserts --rows-per-insert=500 \
    | grep -v '^\\' \
    | sed -e "s/set_config('search_path', '', false)/set_config('search_path', '', true)/" -e 's/^SET /SET LOCAL /' \
    | sed -E "s/'[0-9]{4}-[0-9]{2}-[0-9]{2} [0-9:.]+\+00'\)/'2000-01-01 00:00:00+00')/g" \
    | grep -v '^-- Dumped \(from\|by\)'
} > "$OUT.tmp"
mv "$OUT.tmp" "$OUT"
echo "wrote $OUT ($(wc -l < "$OUT") lines, $(grep -c '^CREATE TABLE' "$OUT") tables)"
