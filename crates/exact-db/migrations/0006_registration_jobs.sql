-- Queue of image registration computations (Rust-owned; the results land in images_imageregistration, shared with EXACT).
-- A Python worker (helpers/registration_worker.py) claims jobs through the API, see exact-api v2/registration.rs.
CREATE TABLE IF NOT EXISTS exact_rust_registration_job (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_image_id bigint NOT NULL REFERENCES images_image(id) ON DELETE CASCADE,
    target_image_id bigint NOT NULL REFERENCES images_image(id) ON DELETE CASCADE,
    params          jsonb  NOT NULL DEFAULT '{}'::jsonb,   -- maxFeatures, ratio, ... as in ImageRegistration.perform_registration
    status          text   NOT NULL DEFAULT 'queued' CHECK (status IN ('queued', 'running', 'done', 'failed')),
    error           text,
    worker          text,
    registration_id bigint REFERENCES images_imageregistration(id) ON DELETE SET NULL,
    created_by      bigint REFERENCES users_user(id) ON DELETE SET NULL,
    created_at      timestamp with time zone NOT NULL DEFAULT now(),
    started_at      timestamp with time zone,
    finished_at     timestamp with time zone,
    lease_expires   timestamp with time zone               -- a running job whose lease ran out is claimed again
);
CREATE INDEX IF NOT EXISTS exact_rust_registration_job_open ON exact_rust_registration_job (status, created_at);
