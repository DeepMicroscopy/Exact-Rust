-- Level registration offsets of image pyramids (see exact-wsi registration.rs): one row per image, estimated once.
-- SHARED with EXACT (Django): the same table is created by the migration `images/0041_pyramidregistration`, with the
-- same DDL. Whichever side runs first creates it; the other is a no-op. Keep both in sync (scripts/check-schema-sync.sh).
CREATE TABLE IF NOT EXISTS images_pyramidregistration (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    image_id   bigint NOT NULL UNIQUE REFERENCES images_image(id) ON DELETE CASCADE DEFERRABLE INITIALLY DEFERRED,
    offsets    jsonb NOT NULL,                       -- [[dx, dy], ...] per pyramid level, in pixels of that level; level 0 is always [0, 0]
    algorithm  smallint NOT NULL,                    -- version of the estimation; rows of other versions are estimated again
    file_size  bigint NOT NULL,                      -- size and mtime (seconds) of the image file the offsets were measured on
    file_mtime bigint NOT NULL,
    updated    timestamp with time zone NOT NULL DEFAULT now()
);
