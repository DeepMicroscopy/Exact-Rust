-- Processing plugins can be registration algorithms, and a job can concern several images and carries parameters.
-- SHARED with EXACT (Django): the same columns are added by the migration `processing/0015_registration_plugins`, with the
-- same DDL. Whichever side runs first adds them; the other is a no-op. Keep both in sync (scripts/check-schema-sync.sh).
ALTER TABLE processing_plugin ADD COLUMN IF NOT EXISTS plugin_type smallint NOT NULL DEFAULT 1;  -- 1 image analysis, 2 registration
ALTER TABLE processing_plugin ADD COLUMN IF NOT EXISTS parameters_schema jsonb;                  -- the parameters a job accepts: [{name, label, type, default, ...}]
ALTER TABLE processing_pluginjob ADD COLUMN IF NOT EXISTS parameters jsonb;                       -- {name: value} of the plugin's parameters for this job (any algorithm)
-- The images a job concerns, in order (position 0 is `processing_pluginjob.image_id`). A registration job has two: the image
-- and the one it is registered onto. A job without rows concerns just its `image`.
CREATE TABLE IF NOT EXISTS processing_pluginjobimage (
    id       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_id   integer NOT NULL REFERENCES processing_pluginjob(id) ON DELETE CASCADE DEFERRABLE INITIALLY DEFERRED,
    image_id bigint NOT NULL REFERENCES images_image(id) ON DELETE CASCADE DEFERRABLE INITIALLY DEFERRED,
    position smallint NOT NULL DEFAULT 0,
    UNIQUE (job_id, position)
);
CREATE INDEX IF NOT EXISTS processing_pluginjobimage_job_id ON processing_pluginjobimage (job_id);
CREATE INDEX IF NOT EXISTS processing_pluginjobimage_image_id ON processing_pluginjobimage (image_id);

-- Rust-owned queue of registration computations: which plugin computes the job (null: the default registration plugin).
ALTER TABLE exact_rust_registration_job ADD COLUMN IF NOT EXISTS plugin_id integer
    REFERENCES processing_plugin(id) ON DELETE SET NULL;
