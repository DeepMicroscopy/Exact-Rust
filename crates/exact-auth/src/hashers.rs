//! Verifies (and creates) Django password hashes so existing accounts keep working after the port.
//! Supported: pbkdf2_sha256 (Django default), pbkdf2_sha1, argon2, bcrypt_sha256, bcrypt.
//! Unknown algorithms and unusable passwords (`!…`) never verify.

use base64::{engine::general_purpose::STANDARD, Engine};
use hmac::Hmac;
use rand::{distributions::Alphanumeric, Rng};
use sha2::{Digest, Sha256};
use subtle::ConstantTimeEq;

pub const DEFAULT_ITERATIONS: u32 = 600_000;

pub fn verify_password(password: &str, encoded: &str) -> bool {
    if encoded.is_empty() || encoded.starts_with('!') {
        return false;
    }
    let Some((algo, rest)) = encoded.split_once('$') else {
        return false;
    };
    match algo {
        "pbkdf2_sha256" => verify_pbkdf2(password, rest, 32, derive_sha256),
        "pbkdf2_sha1" => verify_pbkdf2(password, rest, 20, derive_sha1),
        // Django stores "argon2" + the PHC string ("$argon2id$v=19$…")
        "argon2" => verify_argon2(password, &format!("${rest}")),
        "bcrypt_sha256" => {
            let digest = hex::encode(Sha256::digest(password.as_bytes()));
            bcrypt::verify(digest, rest).unwrap_or(false)
        }
        "bcrypt" => bcrypt::verify(password, rest).unwrap_or(false),
        _ => false,
    }
}

fn verify_pbkdf2(
    password: &str,
    rest: &str,
    len: usize,
    derive: fn(&[u8], &[u8], u32, &mut [u8]),
) -> bool {
    let mut parts = rest.splitn(3, '$');
    let (Some(iters), Some(salt), Some(hash)) = (parts.next(), parts.next(), parts.next()) else {
        return false;
    };
    let Ok(iters) = iters.parse::<u32>() else {
        return false;
    };
    let Ok(expected) = STANDARD.decode(hash) else {
        return false;
    };
    if expected.len() != len || iters == 0 {
        return false;
    }
    let mut out = vec![0u8; len];
    derive(password.as_bytes(), salt.as_bytes(), iters, &mut out);
    out.ct_eq(&expected).into()
}

fn derive_sha256(pw: &[u8], salt: &[u8], iters: u32, out: &mut [u8]) {
    pbkdf2::pbkdf2::<Hmac<Sha256>>(pw, salt, iters, out).expect("hmac accepts any key length");
}

fn derive_sha1(pw: &[u8], salt: &[u8], iters: u32, out: &mut [u8]) {
    pbkdf2::pbkdf2::<Hmac<sha1::Sha1>>(pw, salt, iters, out).expect("hmac accepts any key length");
}

fn verify_argon2(password: &str, phc: &str) -> bool {
    use argon2::password_hash::{PasswordHash, PasswordVerifier};
    PasswordHash::new(phc)
        .map(|h| {
            argon2::Argon2::default()
                .verify_password(password.as_bytes(), &h)
                .is_ok()
        })
        .unwrap_or(false)
}

/// New hash in Django's default format (used for password resets / registration).
pub fn make_password(password: &str) -> String {
    let salt: String = rand::thread_rng()
        .sample_iter(&Alphanumeric)
        .take(22)
        .map(char::from)
        .collect();
    let mut out = [0u8; 32];
    derive_sha256(
        password.as_bytes(),
        salt.as_bytes(),
        DEFAULT_ITERATIONS,
        &mut out,
    );
    format!(
        "pbkdf2_sha256${DEFAULT_ITERATIONS}${salt}${}",
        STANDARD.encode(out)
    )
}

#[cfg(test)]
mod tests {
    use super::*;

    // Generated by Django 4.2 (make_password) for the password below.
    const PW: &str = "pässword-1";
    const PBKDF2_SHA256: &str =
        "pbkdf2_sha256$600000$045SWG5IuT0zsUdU1Fp7Bk$5JhcElNrVu48qa93yztog78YclLDW8Vi622OCA3IyuA=";
    const PBKDF2_SHA1: &str =
        "pbkdf2_sha1$600000$8i9WOVXyjdy720cwftUk3M$weEox67K84/J2eNM0/aYzrKed6E=";
    const ARGON2: &str = "argon2$argon2id$v=19$m=102400,t=2,p=8$MFNGRUZmQ3RyNjVReExGQjNqR0pzZQ$OhO7GqNFDc+4p4e6ibwJyVsOEFniQBi81lFo7BzNYLo";
    const BCRYPT_SHA256: &str =
        "bcrypt_sha256$$2b$12$urI8KWm3TumGS7VXJTUcIOOOhTfLPlYJ/smHqkaXFiEZl05jLkaeC";
    const BCRYPT: &str = "bcrypt$$2b$12$FQcXf0krBe1EWVJnQEEFM.U5ECjkXdoZ40bMgwn4GYFquIwIz7E4O";

    #[test]
    fn verifies_all_django_formats() {
        for h in [PBKDF2_SHA256, PBKDF2_SHA1, ARGON2, BCRYPT_SHA256, BCRYPT] {
            assert!(verify_password(PW, h), "{h}");
            assert!(!verify_password("wrong", h), "{h}");
        }
    }

    #[test]
    fn rejects_unusable_unknown_and_malformed() {
        assert!(!verify_password(PW, "!abcdef"));
        assert!(!verify_password(PW, ""));
        assert!(!verify_password(PW, "md5$salt$hash"));
        assert!(!verify_password(PW, "pbkdf2_sha256$x$y"));
        assert!(!verify_password(
            PW,
            "pbkdf2_sha256$600000$salt$not-base64!"
        ));
    }

    #[test]
    fn make_password_roundtrips() {
        let h = make_password("s3cret");
        assert!(h.starts_with("pbkdf2_sha256$600000$"));
        assert!(verify_password("s3cret", &h) && !verify_password("s3cret ", &h));
    }
}
